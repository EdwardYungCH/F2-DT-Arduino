"""End-to-end test of lesson 6 (RGB mood lamp) with deliberate mistakes."""
import asyncio, os, sys
from playwright.async_api import async_playwright
URL = 'file://' + os.path.abspath(os.path.dirname(__file__) + '/../lesson6/index.html')
OUT = os.environ.get('OUT', '/tmp/l6-test/'); os.makedirs(OUT, exist_ok=True)
BIN = lambda i: 84 + i * 112
TRASH = (1050, 560)
FAIL = []
def ok(cond, msg):
    print(('PASS ' if cond else 'FAIL ') + msg)
    if not cond: FAIL.append(msg)
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        ctx = await b.new_context(viewport={'width': 1440, 'height': 900}, accept_downloads=True)
        pg = await ctx.new_page(); errs = []
        pg.on('pageerror', lambda e: errs.append('PAGEERR ' + str(e)))
        await pg.goto(URL); await pg.wait_for_timeout(1000)
        ok('analogWrite' in await pg.inner_text('#heroRead'), 'login: lamp demo shows analogWrite values')
        await pg.screenshot(path=OUT + '01-login.png')
        await pg.fill('#inName', '黃小華'); await pg.fill('#inCls', '2C'); await pg.fill('#inNo', '5')
        await pg.click('#loginBtn'); await pg.wait_for_timeout(600)
        await pg.click('#introMixer [data-preset="255,255,0"]'); await pg.wait_for_timeout(100)
        ok('黃色' in await pg.inner_text('#introMixer [data-mixname]'), 'intro mixer: red + green = yellow')
        ok('analogWrite(greenPin, 255);' in await pg.inner_text('#introMixer [data-mixcode]'), 'intro mixer shows the code')
        await pg.screenshot(path=OUT + '02-intro.png', full_page=True)
        await pg.click('#introNext'); await pg.wait_for_timeout(400)
        async def c(x, y): return await pg.evaluate('''([x,y])=>{const s=document.querySelector('#hwSvg');const pt=s.createSVGPoint();pt.x=x;pt.y=y;const r=pt.matrixTransform(s.getScreenCTM());return [r.x,r.y]}''', [x, y])
        async def drag(a, bb):
            ax, ay = await c(*a); bx, by = await c(*bb)
            await pg.mouse.move(ax, ay); await pg.mouse.down()
            for i in range(1, 8): await pg.mouse.move(ax + (bx - ax) * i / 7, ay + (by - ay) * i / 7)
            await pg.mouse.up(); await pg.wait_for_timeout(120)
        P = await pg.evaluate('()=>{const o={};for(const k in HW.P) o[k]=[HW.P[k].x,HW.P[k].y];return o}')
        H = lambda k, dx=0, dy=0: (P[k][0] + dx, P[k][1] + dy)
        async def check(n, label=''):
            await pg.click(f'[data-check="{n}"]'); await pg.wait_for_timeout(150)
            t = (await pg.inner_text('#hwIssues')).replace('\n', ' ')
            print(f'   step {n} {label}:', t[:150]); return t
        async def wire(a, bb, color=None):
            if color is not None: await pg.click(f'#swatches .sw:nth-child({color})')
            await drag(H(a), H(bb))
        # 1 RGB LED (grab the dome: tray legs are at cx-30 … cx+30, y 592)
        await drag((BIN(0), 566), H('f13', 30, -26))
        parts = await pg.evaluate('()=>S.hw.parts.map(p=>p.type+p.h1)')
        ok(parts == ['rgbf13'], f'RGB LED placed at f13 {parts}')
        ok('正確' in await check(1), 'step 1 RGB LED placed')
        # 2 a 10kΩ on green by mistake
        await drag((BIN(2), 574), H('h9', 40)); await drag((BIN(1), 574), H('i14', 40)); await drag((BIN(1), 574), H('h16', 40))
        t = await check(2, '10k on green')
        ok('220Ω' in t and '已記錄 1 次' in t, 'step 2: 10kΩ on a colour is an error')
        await pg.screenshot(path=OUT + '03-res-error.png')
        await drag(H('h9', 40), TRASH)
        await drag((BIN(1), 574), H('h9', 40))
        ok('正確' in await check(2), 'step 2 fixed with three 220Ω')
        # 3 GND + longest leg
        await wire('P:GND', 'tn8', 1)
        t = await check(3, 'no K wire')
        ok('最長的腳' in t and '已記錄' not in t, 'step 3 reminds the longest leg (hint only)')
        await wire('j15', 'tn15', 1)
        ok('正確' in await check(3), 'step 3 GND and longest leg')
        # 4 red on D8 (no ~)
        await wire('P:D8', 'j20', 2)
        t = await check(4, 'D8')
        ok('~' in t and '已記錄' in t, 'step 4: D8 has no ~ (counted)')
        await drag(H('P:D8'), TRASH)
        await wire('P:D9', 'j20', 2)
        ok('正確' in await check(4), 'step 4 D9')
        # 5 green and blue
        await wire('P:D10', 'j9', 5); await wire('P:D11', 'j18', 4)
        ok('正確' in await check(5), 'step 5 D10 and D11')
        await check(6)
        hw = await pg.evaluate('()=>({e:S.hw.errors,h:S.hw.hints,done:S.hw.done})')
        ok(hw['done'] and hw['e'] == 2, f'wiring done with 2 errors {hw}')
        await pg.screenshot(path=OUT + '05-hw-done.png')
        await pg.click('.modal .actions .btn.go'); await pg.wait_for_timeout(300)
        # ---- code ----
        ok(await pg.is_visible('#labMix'), 'colour mixer is shown next to the blanks')
        await pg.click('#labMix [data-preset="0,255,255"]'); await pg.wait_for_timeout(100)
        ok('青色' in await pg.inner_text('#labMix [data-mixname]'), 'mixer: green + blue = cyan')
        await pg.screenshot(path=OUT + '06-code.png')
        for k, v in {'b1': 'D11', 'b2': 'output', 'b3': 'digitalWrite', 'b4': '0', 'b5': '0', 'b6': '300', 'b7': '0', 'b8': '0'}.items():
            await pg.fill('#blank-' + k, v)
        await pg.click('[data-menu="tools"]'); await pg.hover('.menu .mi:has-text("Board")'); await pg.hover('.menu .mi:has-text("Arduino AVR Boards")')
        await pg.click('.menu .mi span:text-is("Arduino Uno")'); await pg.wait_for_timeout(100)
        await pg.click('#btnVerify'); await pg.wait_for_timeout(1700)
        out = await pg.inner_text('#ideOut'); print(out[:500])
        ok("'D11' was not declared" in out and 'Mood_Lamp.ino:6:' in out, "compile: 'D11' undeclared on line 6")
        ok("'output' was not declared" in out and "suggested alternative: 'OUTPUT'" in out, 'compile: output → OUTPUT suggestion')
        await pg.click('#btnCheck'); await pg.wait_for_timeout(200)
        lst = (await pg.inner_text('#codePanel .blist')).replace('\n', ' | ')
        ok('不用寫 D' in lst and '全開或全關' in lst and '255' in lst and '大小寫' in lst, 'feedback: D11, digitalWrite, >255, case')
        await pg.screenshot(path=OUT + '07-code-err.png')
        for k, v in {'b1': '11', 'b2': 'OUTPUT', 'b3': 'analogWrite', 'b4': '255', 'b6': '0'}.items(): await pg.fill('#blank-' + k, v)
        await pg.click('#btnCheck'); await pg.wait_for_timeout(200)
        ok('三格都是 0' in await pg.inner_text('#codePanel .blist'), 'an all-zero mood colour is rejected')
        for k, v in {'b6': '255', 'b7': '40', 'b8': '120'}.items(): await pg.fill('#blank-' + k, v)
        await pg.click('#btnCheck'); await pg.wait_for_timeout(200); await pg.click('.modal .actions .btn.go')
        ok(await pg.evaluate('()=>S.code.done'), 'all blanks correct (mood 255, 40, 120)')
        await pg.click('#btnUpload'); await pg.wait_for_timeout(1900)
        ok('連接埠' in await pg.inner_text('#codeExplain'), 'upload without port fails')
        await pg.click('#btnUsb'); await pg.click('[data-menu="tools"]'); await pg.hover('.menu .mi:has-text("Port")'); await pg.click('.menu .mi:has-text("(Arduino Uno)")')
        await pg.click('#btnUpload'); await pg.wait_for_timeout(4300)
        ok(await pg.is_visible('#rgbSeq'), 'result shows the running sequence')
        await pg.wait_for_timeout(2300)
        now_txt = await pg.inner_text('#rgbNow')
        glow = await pg.evaluate("()=>+document.querySelector('.modal .rgbglow').getAttribute('opacity')")
        ok('120' in now_txt and '粉紅色' in now_txt and glow > 0.9, f'sequence reaches the mood colour ({now_txt}, glow {glow})')
        await pg.screenshot(path=OUT + '08-result.png')
        await pg.click('.modal [data-preset="255,255,255"]'); await pg.wait_for_timeout(200)
        ok('白色' in await pg.inner_text('#rgbNow') and await pg.is_visible('#rgbResume'), 'free mixing pauses the program and shows white')
        await pg.click('.modal .actions .btn.go'); await pg.wait_for_timeout(400)
        # real page
        code = await pg.input_value('#codeText')
        ok('analogWrite(greenPin, 40);' in code and 'analogWrite(bluePin, 120);' in code, "full program uses the student's mood colour")
        ok('粉紅色' in await pg.inner_text('#st-real'), 'real page names the mood colour')
        await pg.click('#shadeCb')
        await pg.screenshot(path=OUT + '10-real.png', full_page=True)
        await pg.click('#toReport'); await pg.click('.modal .actions .btn.go'); await pg.wait_for_timeout(500)
        rec = await pg.evaluate('()=>buildRecord()')
        print('score', rec['score'])
        ok(rec['score']['hw'] == 32 and rec['score']['code'] < 40 and rec['score']['up'] == 17, f"scores {rec['score']}")
        ok(rec['real']['mood'] == [255, 40, 120] and rec['real']['shade'] is True, f"record keeps mood colour and lampshade {rec['real']}")
        ok([b['ans'] for b in rec['code']['blanks']][5:] == ['255', '40', '120'], 'report table shows the student mood values')
        await pg.screenshot(path=OUT + '11-report.png', full_page=True)
        async with pg.expect_download() as dl: await pg.click('#dlReport')
        d = await dl.value; path = OUT + 'report.html'; await d.save_as(path)
        ok(d.suggested_filename.startswith('RGB心情燈_2C_5'), 'file ' + d.suggested_filename)
        rp = await ctx.new_page(); await rp.goto('file://' + path); await rp.wait_for_timeout(300)
        rt = await rp.inner_text('#r')
        ok('驗證碼有效' in rt and '我的心情色' in rt and '120' in rt, 'report file valid and shows the mood colour')
        txt = open(path, encoding='utf-8').read().replace('\\"total\\":', '\\"total\\":1', 1)
        open(OUT + 'tampered.html', 'w', encoding='utf-8').write(txt)
        await rp.goto('file://' + OUT + 'tampered.html'); await rp.wait_for_timeout(300)
        ok('驗證失敗' in await rp.inner_text('.rver'), 'tampered report fails')
        await pg.click('#teacherBtn'); await pg.fill('#pwIn', 'dt2026'); await pg.click('.modal .btn.primary'); await pg.wait_for_timeout(200)
        await pg.click('#tpVerify'); await pg.set_input_files('#vFile', [path, OUT + 'tampered.html', os.path.abspath(os.path.dirname(__file__) + '/../lesson4/index.html')]); await pg.wait_for_timeout(400)
        vt = await pg.inner_text('#vTbl'); print(vt)
        ok('有效' in vt and '無效' in vt and ('不是 RGB 心情燈成績報告' in vt or '檔案損壞' in vt), 'verifier rejects tampered and non-report files')
        async with pg.expect_download() as dl2: await pg.click('#vCsv')
        d2 = await dl2.value; await d2.save_as(OUT + 'out.csv'); csv = open(OUT + 'out.csv', encoding='utf-8-sig').read(); print(csv)
        ok('心情色:紅' in csv and ',255,40,120,是,' in csv, 'CSV has the mood colour and lampshade')
        errs = [e for e in errs if 'ERR_TUNNEL' not in e]
        ok(not errs, f'no page errors {errs}')
        await b.close()
    print('FAILURES:', FAIL)
    sys.exit(1 if FAIL else 0)
asyncio.run(main())
